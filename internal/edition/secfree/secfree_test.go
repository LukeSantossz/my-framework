func TestBuildFailsWhenADeclaredInputIsMissing(t *testing.T) {
	o := fixture(t)
	if err := os.Remove(filepath.Join(o.RepoRoot, "docs", "editions", "secfree", "isolated_review.md")); err != nil {
		t.Fatal(err)
	}
	if _, err := Build(o); err == nil {
		t.Fatal("the build passed with a declared input missing")
	}
}

func TestBuildWritesNothingWhenItFails(t *testing.T) {
	o := fixture(t)
	write(t, o.RepoRoot, "docs/standards/github.md", "Run `mf check`.\n")
	if _, err := Build(o); err == nil {
		t.Fatal("expected a failure")
	}
	if _, err := os.Stat(o.Out); !os.IsNotExist(err) {
		t.Errorf("a failed build left %s behind (stat: %v)", o.Out, err)
	}
}

func TestBuildRefusesAnOutputDirectoryThatIsNotEmpty(t *testing.T) {
	o := fixture(t)
	write(t, o.Out, "keep.txt", "someone's file\n")
	if _, err := Build(o); err == nil {
		t.Fatal("the build wrote into a directory that already held files")
	}
	if got := read(t, o.Out, "keep.txt"); got != "someone's file\n" {
		t.Errorf("an existing file was touched: %q", got)
	}
}
