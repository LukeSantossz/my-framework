const instructions = `# Agent Instructions

<!-- mf:edition full secfree=preamble -->
Every vendor file is generated by ` + "`mf agents sync`" + `.
<!-- mf:edition end -->

Read ` + "`docs/standards/INDEX.md`" + ` first.

<!-- mf:role shared -->
## Standards are binding

Follow the standards.

<!-- mf:role author -->
## Your role as Author

Specify before building.
<!-- mf:edition full -->
Run ` + "`mf check`" + ` before the pre-push hook does.
<!-- mf:edition end -->

<!-- mf:role reviewer -->
## Your role as Reviewer (R2)

<!-- mf:edition full secfree=reviewer -->
You are a different provider from the Author.
<!-- mf:edition end -->
`

// fixture lays out a repository carrying everything the edition reads, plus a
// standard the edition leaves out, and returns options pointed at it.
func fixture(t *testing.T) Options {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"LICENSE":                                        "MIT License\n",
		"docs/agents/instructions.md":                    instructions,
		"docs/editions/secfree/README.md":                "# my-framework, sec-free edition\n",
		"docs/editions/secfree/isolated_review.md":       "# Isolated-Context Review\n",
		"docs/editions/secfree/snippets/preamble.md":     "These files are published read-only.\n",
		"docs/editions/secfree/snippets/reviewer.md":     "You run in a context that did not author the change.\n",
		"docs/editions/secfree/snippets/index-review.md": "- `isolated_review.md`: R2 and R3 in isolated contexts.\n",
		"docs/standards/r2_gate.md":                      "Run `mf review --role r2`; codex reviews.\n",
	}
	for _, name := range standards {
		files["docs/standards/"+name] = "# " + name + "\n\nA rule.\n"
	}
	files["docs/standards/INDEX.md"] = "# Index\n\n- `spec_method.md`: specs.\n" +
		"<!-- mf:edition full secfree=index-review -->\n- `r2_gate.md`: the codex gate.\n<!-- mf:edition end -->\n"
	for name, body := range files {
		write(t, root, name, body)
	}
	return Options{
		RepoRoot:     root,
		StandardsDir: "docs/standards",
		AgentsSource: "docs/agents/instructions.md",
		Out:          filepath.Join(t.TempDir(), "out"),
		Forbidden:    []string{"codex", "coderabbit"},
	}
}

func write(t *testing.T, root, name, body string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, dir, name string) string {
	t.Helper()
	body, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
	if err != nil {
		t.Fatal(err)
	}
	return string(body)
}

func listed(t *testing.T, dir string) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			rel, _ := filepath.Rel(dir, path)
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(out)
	return out
}

func TestBuildWritesExactlyTheDeclaredFileSet(t *testing.T) {
	o := fixture(t)
	if _, err := Build(o); err != nil {
		t.Fatal(err)
	}
	want := []string{
		"AGENTS.md", "CLAUDE.md", "LICENSE", "README.md",
		"docs/standards/INDEX.md",
		"docs/standards/ai_guidelines.md",
		"docs/standards/code_conventions.md",
		"docs/standards/crura_method.md",
		"docs/standards/github.md",
		"docs/standards/isolated_review.md",
		"docs/standards/spec_method.md",
		"docs/standards/token_economy.md",
		"docs/standards/var_method.md",
	}
	got := listed(t, o.Out)
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("got files:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestBuildOutputContainsNoExecutableBitScriptExtensionHookOrGitmodules(t *testing.T) {
	o := fixture(t)
	if _, err := Build(o); err != nil {
		t.Fatal(err)
	}
	err := filepath.WalkDir(o.Out, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		name := d.Name()
		if ext := filepath.Ext(name); ext != ".md" && name != "LICENSE" {
			t.Errorf("%s is neither Markdown nor the licence", path)
		}
		if strings.HasPrefix(name, ".git") || strings.Contains(filepath.ToSlash(path), ".githooks") {
			t.Errorf("%s is git machinery the edition must not carry", path)
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		// Windows has no executable bit to inspect; everywhere else it must be off.
		if runtime.GOOS != "windows" && info.Mode()&0o111 != 0 {
			t.Errorf("%s is executable (%v)", path, info.Mode())
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

func TestBuildStripsEveryFullOnlyRegionAndSubstitutesItsSnippet(t *testing.T) {
	o := fixture(t)
	if _, err := Build(o); err != nil {
		t.Fatal(err)
	}
	index := read(t, o.Out, "docs/standards/INDEX.md")
	if strings.Contains(index, "r2_gate") {
		t.Errorf("INDEX.md kept a full-only line:\n%s", index)
	}
	if !strings.Contains(index, "isolated_review.md") {
		t.Errorf("INDEX.md lacks the substituted snippet:\n%s", index)
	}
	if got := read(t, o.Out, "docs/standards/isolated_review.md"); got != "# Isolated-Context Review\n" {
		t.Errorf("isolated_review.md = %q", got)
	}
}

func TestEditionInstructionsCarryTheAuthorAndReviewerSections(t *testing.T) {
	o := fixture(t)
	if _, err := Build(o); err != nil {
		t.Fatal(err)
	}
	for _, file := range []string{"CLAUDE.md", "AGENTS.md"} {
		body := read(t, o.Out, file)
		for _, want := range []string{
			"Standards are binding", "Your role as Author", "Your role as Reviewer",
			"published read-only", "did not author the change", "Do not edit",
		} {
			if !strings.Contains(body, want) {
				t.Errorf("%s lacks %q:\n%s", file, want, body)
			}
		}
		if strings.Contains(body, "mf:") {
			t.Errorf("%s still carries a marker:\n%s", file, body)
		}
	}
}

func TestBuildFailsWhenOutputStillInvokesTheBinaryOrNamesAHook(t *testing.T) {
	for name, line := range map[string]string{
		"binary":     "Run `mf check` first.\n",
		"pre-push":   "The pre-push hook stops it.\n",
		"commit-msg": "The commit-msg hook checks the subject.\n",
		"hooksPath":  "Point core.hooksPath at the hooks.\n",
	} {
		t.Run(name, func(t *testing.T) {
			o := fixture(t)
			write(t, o.RepoRoot, "docs/standards/github.md", "# github\n\n"+line)
			_, err := Build(o)
			if err == nil {
				t.Fatal("the build passed a document that still relies on the binary")
			}
			if !strings.Contains(err.Error(), "docs/standards/github.md:3") {
				t.Errorf("error does not name the file and line: %v", err)
			}
		})
	}
}

func TestBuildFailsWhenOutputNamesAVendorBackendCommandOrForgeApp(t *testing.T) {
	for _, line := range []string{"Codex reviews it.\n", "CodeRabbit comments on the PR.\n"} {
		o := fixture(t)
		write(t, o.RepoRoot, "docs/standards/ai_guidelines.md", "# ai\n\n"+line)
		if _, err := Build(o); err == nil {
			t.Errorf("the build passed %q", line)
		}
	}
}

func TestBuildFailsWhenOutputCitesAStandardTheEditionLeavesOut(t *testing.T) {
	// r2_gate.md is in the fixture's corpus and not in the edition, so a
	// reference to it would send a reader to a document they were never given.
	o := fixture(t)
	write(t, o.RepoRoot, "docs/standards/github.md", "# github\n\nRecord the layers per `r2_gate.md`.\n")
	_, err := Build(o)
	if err == nil || !strings.Contains(err.Error(), "github.md:3") {
		t.Fatalf("expected a failure at github.md:3, got %v", err)
	}
}

