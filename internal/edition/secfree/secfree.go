// Package secfree assembles the sec-free edition: the documents-only tree
// published on the orphan `secfree` branch for environments where no framework
// executable may run (spec 0052).
//
// Nothing in the edition runs, so nothing in it can check itself. Every check
// the edition needs therefore happens here, on the maintainer's side, before a
// single file is written: a full-only region left unmarked, a hook still named,
// a vendor backend still cited — each is a build failure naming the file and
// line, and a failed build writes nothing.
package secfree

import (
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/LukeSantossz/my-framework/internal/agents"
	"github.com/LukeSantossz/my-framework/internal/edition"
)

// EditionDir holds what exists only in the sec-free edition: its README, the
// isolated-review standard, and the snippets a full-only region is replaced by.
const EditionDir = "docs/editions/secfree"

// standards are the documents of the full corpus the edition carries. The rest
// describe the binary, its vendor backends or the surfaces it renders, and an
// edition that cannot run it has no use for them.
var standards = []string{
	"INDEX.md",
	"spec_method.md",
	"code_conventions.md",
	"var_method.md",
	"github.md",
	"crura_method.md",
	"ai_guidelines.md",
	"token_economy.md",
}

// roles are every role the edition's instruction files carry. One model plays
// all of them here, in separate contexts, so each file holds the whole set.
var roles = []string{"shared", "author", "reviewer"}

// instructionFiles are the vendor files the edition ships, already generated.
var instructionFiles = []string{"CLAUDE.md", "AGENTS.md"}

const header = "<!-- Generated for the sec-free edition of my-framework from its agent\n" +
	"     instruction source. Do not edit this file: the edition is published\n" +
	"     read-only, and a change to it is a change to the framework's source. -->\n"

// Options says where the inputs are and where the edition goes.
type Options struct {
	// RepoRoot is the framework checkout the edition is cut from.
	RepoRoot string
	// StandardsDir and AgentsSource are relative to RepoRoot, as configured.
	StandardsDir string
	AgentsSource string
	// Out is the directory the edition is written to. It must not exist or be
	// empty: a build never mixes its tree with files it did not write.
	Out string
	// Forbidden are names the edition must never mention — every backend name
	// and command the repository's policy declares. Taken from configuration so
	// a backend added to a chain is forbidden here without touching this code.
	Forbidden []string
}

// Build assembles the edition and returns the paths it wrote, relative to Out
// and sorted.
func Build(o Options) ([]string, error) {
	files, err := assemble(o)
	if err != nil {
		return nil, err
	}
	if problems := scan(files, o.Forbidden); len(problems) > 0 {
		return nil, fmt.Errorf("the edition still depends on what it cannot run:\n  %s", strings.Join(problems, "\n  "))
	}
	if err := ensureEmpty(o.Out); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		dest := filepath.Join(o.Out, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(dest, []byte(files[name]), 0o644); err != nil {
			return nil, err
		}
	}
	return names, nil
}

// assemble produces every file of the edition in memory, keyed by its path in
// the edition, so nothing is written until all of it has been checked.
func assemble(o Options) (map[string]string, error) {
	readRepo := func(rel string) (string, error) {
		body, err := os.ReadFile(filepath.Join(o.RepoRoot, filepath.FromSlash(rel)))
		if err != nil {
			return "", fmt.Errorf("cannot read %s: %w", rel, err)
		}
		return string(body), nil
	}
	snippet := func(name string) (string, error) {
		return readRepo(path.Join(EditionDir, "snippets", name+".md"))
	}
	strip := func(rel string) (string, error) {
		body, err := readRepo(rel)
		if err != nil {
			return "", err
		}
		out, err := edition.Strip(body, snippet)
		if err != nil {
			return "", fmt.Errorf("%s: %w", rel, err)
		}
		return out, nil
	}

	files := map[string]string{}
	for _, name := range standards {
		body, err := strip(path.Join(o.StandardsDir, name))
		if err != nil {
			return nil, err
		}
		files["docs/standards/"+name] = body
	}
	copies := map[string]string{
		"README.md":                         path.Join(EditionDir, "README.md"),
		"docs/standards/isolated_review.md": path.Join(EditionDir, "isolated_review.md"),
		"LICENSE":                           "LICENSE",
	}
	for dest, src := range copies {
		body, err := readRepo(src)
		if err != nil {
			return nil, err
		}
		files[dest] = body
	}

	source, err := strip(o.AgentsSource)
	if err != nil {
		return nil, err
	}
	instructions, err := compose(source)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", o.AgentsSource, err)
	}
	for _, name := range instructionFiles {
		files[name] = instructions
	}
	return files, nil
}

// compose renders the edition's instruction file from the stripped source. It
// does not go through agents.Render, whose header sends the reader to a command
// this edition does not have.
func compose(source string) (string, error) {
	src, err := agents.Parse(source)
	if err != nil {
		return "", err
	}
	declared := map[string]bool{}
	for _, r := range src.Roles() {
		declared[r] = true
	}
	wanted := map[string]bool{}
	for _, r := range roles {
		if !declared[r] {
			return "", fmt.Errorf("the source declares no %q role, which the edition's instruction files must carry", r)
		}
		wanted[r] = true
	}
	var b strings.Builder
	b.WriteString(header)
	if src.Preamble != "" {
		b.WriteString("\n")
		b.WriteString(src.Preamble)
		b.WriteString("\n")
	}
	for _, sec := range src.Sections {
		if !wanted[sec.Role] {
			continue
		}
		b.WriteString("\n")
		b.WriteString(sec.Body)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// rule is one thing the edition must never say, and why.
type rule struct {
	pattern *regexp.Regexp
	reason  string
}

func rules(forbidden []string) []rule {
	out := []rule{
		{regexp.MustCompile(`\bmf\b`), "names the framework binary"},
		{regexp.MustCompile(`(?i)pre-push|commit-msg|hooksPath|\.githooks`), "names a git hook"},
	}
	seen := map[string]bool{}
	for _, name := range forbidden {
		name = strings.TrimSpace(name)
		if name == "" || seen[strings.ToLower(name)] {
			continue
		}
		seen[strings.ToLower(name)] = true
		out = append(out, rule{
			regexp.MustCompile(`(?i)\b` + regexp.QuoteMeta(name) + `\b`),
			fmt.Sprintf("names the backend %q, which sends code to a vendor or runs a program", name),
		})
	}
	return out
}

// scan reports every line of the edition that breaks a rule, as file:line.
func scan(files map[string]string, forbidden []string) []string {
	rs := rules(forbidden)
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var problems []string
	for _, name := range names {
		for i, line := range strings.Split(files[name], "\n") {
			for _, r := range rs {
				if r.pattern.MatchString(line) {
					problems = append(problems,
						fmt.Sprintf("%s:%d %s: %s", name, i+1, r.reason, strings.TrimSpace(line)))
				}
			}
		}
	}
	return problems
}

// ensureEmpty accepts a directory that does not exist or holds nothing.
func ensureEmpty(dir string) error {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if len(entries) > 0 {
		return fmt.Errorf("%s is not empty; the edition is written only into an empty or new directory", dir)
	}
	return nil
}
